import fs from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const shell = [
  "index.html",
  "css/style.css",
  "js/start.js",
  "js/engine.js",
  "js/logic.js",
  "js/progress.js",
  "js/content.js",
  "js/math.js",
  "js/pwa.js",
  "manifest.webmanifest",
  "assets/mark.svg",
  "assets/icons/icon-192.png",
  "assets/icons/icon-512.png",
  "assets/icons/icon-maskable-512.png",
  "assets/icons/apple-touch-icon.png",
  "courses/corporate-finance/course.json",
];
const course = JSON.parse(
  fs.readFileSync(new URL("courses/corporate-finance/course.json", root)),
);
const paths = [
  ...new Set([
    ...shell,
    ...course.units.flatMap((u) =>
      u.lessons.map((l) => `courses/corporate-finance/${l.file}`),
    ),
    "assets/katex/katex.min.js",
    "assets/katex/auto-render.min.js",
    "assets/katex/katex.min.css",
    ...fs
      .readdirSync(new URL("assets/katex/fonts/", root))
      .filter((f) => f.endsWith(".woff2"))
      .sort()
      .map((f) => `assets/katex/fonts/${f}`),
  ]),
];
const entry = new URL("index.html", root);
const currentHtml = fs.readFileSync(entry, "utf8");
const normalize = (html) =>
  html
    .replace(/(name="finpath-release"\s+content=")[^"]+/, "$1RELEASE")
    .replace(/(\?release=)[a-f0-9]+/g, "$1RELEASE");
const releaseHash = createHash("sha256");
for (const path of paths) {
  releaseHash.update(path);
  releaseHash.update(
    path === "index.html"
      ? normalize(currentHtml)
      : fs.readFileSync(new URL(path, root)),
  );
}
releaseHash.update(fs.readFileSync(new URL("sw.js", root)));
const release = releaseHash.digest("hex").slice(0, 16);
const html = normalize(currentHtml).replaceAll("RELEASE", release);
if (process.argv.includes("--check")) {
  if (currentHtml !== html)
    throw new Error("Stale entry release. Run npm run pwa:assets.");
} else fs.writeFileSync(entry, html);
const files = paths.map((path) => {
  const bytes = fs.readFileSync(new URL(path, root));
  return {
    path,
    sha256: createHash("sha256").update(bytes).digest("hex"),
    bytes: bytes.length,
    shell: shell.includes(path),
  };
});
// Worker code contributes to the release, so behavior changes also get a fresh cache.
const version = createHash("sha256")
  .update(JSON.stringify(files))
  .update(fs.readFileSync(new URL("sw.js", root)))
  .digest("hex")
  .slice(0, 16);
// CDN HTML rewriting must not alter the verified shell saved for offline use.
const source = `// Generated by npm run pwa:assets. Commit this with every app/content change.\nself.FINPATH_ASSETS = ${JSON.stringify({ version, release, files, html }, null, 2)};\n`;
const target = new URL("sw-assets.js", root);
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8") !== source)
    throw new Error("Stale PWA asset index. Run npm run pwa:assets.");
} else fs.writeFileSync(target, source);
console.log(
  `PWA ${version}: ${files.length} files, ${files.reduce((sum, f) => sum + f.bytes, 0)} bytes total. ${fileURLToPath(target)}`,
);
